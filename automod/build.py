"""Regenerates automod.js and setup/slur_filter.sql from TERMS in gen_filter.py.
Run from the repo root:   python3 automod/build.py
"""
import json, os, sys
sys.path.insert(0, os.path.dirname(__file__))
import gen_filter

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
js_re, pg = gen_filter.build(False), gen_filter.build(True)

JS_HEAD = '// ===== auto-mod: hateful-language filter (generated by gen_filter.py, mirrors the database trigger in slur_filter.sql) =====\n// Catches look-alike characters (1 ! | @ 3 0 $ ...), repeated letters, separators (n.i.g.g.e.r), full-width and\n// Cyrillic/Greek homoglyphs, but not innocent words that merely contain a term (snigger, niggardly, raccoon...).\n// The browser check is a convenience; the database trigger is what actually enforces it.\nconst SLUR_RE=new RegExp('
JS_TAIL = ",'iu');\nconst _HOMO_FROM='аеорсхіуѕјονιαε',_HOMO_TO='aeopcxiysjoviae';\nfunction slurNorm(t){\n  return String(t).slice(0,4000).normalize('NFKD').replace(/[\\u0300-\\u036f\\u200b-\\u200d\\u2060\\ufeff\\u00ad]/g,'').toLowerCase()\n    .replace(/[аеорсхіуѕјονιαε]/g,c=>_HOMO_TO[_HOMO_FROM.indexOf(c)]);\n}\nfunction hasSlur(t){return !!t&&SLUR_RE.test(slurNorm(t))}\n// returns true (and tells the user) when the text must not be sent\nfunction slurBlock(t,what){\n  if(!hasSlur(t))return false;\n  alert((what||'That message')+' was blocked by auto-mod: hateful language is not allowed.');\n  return true;\n}\n"
open(os.path.join(root, 'automod.js'), 'w', encoding='utf8').write(JS_HEAD + json.dumps(js_re) + JS_TAIL)

SQL = f'''-- BEANCORD slur filter (server side). Run once in the Supabase SQL editor. Safe to re-run.
-- It rejects inserts/edits whose text matches the same pattern the browser uses (automod/automod.js),
-- so the filter still works if someone calls the API directly. The error text starts with "auto-mod"
-- so the site's existing handling for blocked messages kicks in.
-- To change the word list, edit automod/gen_filter.py (TERMS), re-run it, and re-run this file.

create or replace function public.bc_has_slur(txt text) returns boolean
language plpgsql immutable as $fn$
declare t text;
begin
  if txt is null or txt = '' then return false; end if;
  t := lower(left(txt, 4000));
  t := normalize(t, NFKD);
  t := regexp_replace(t, '[\\u0300-\\u036f\\u200b-\\u200d\\u2060\\ufeff\\u00ad]', '', 'g');
  t := translate(t, 'аеорсхіуѕјονιαε', 'aeopcxiysjoviae');   -- cyrillic/greek look-alikes
  return t ~* $re${pg}$re$;
end $fn$;

create or replace function public.bc_block_slurs() returns trigger
language plpgsql as $fn$
begin
  -- service-role callers (edge functions, the bot) are trusted
  if coalesce(nullif(current_setting('request.jwt.claims', true), '')::json ->> 'role', '') = 'service_role' then
    return new;
  end if;
  if public.bc_has_slur(new.content) then
    raise exception 'auto-mod: that message contains blocked language';
  end if;
  return new;
end $fn$;

create or replace function public.bc_block_slurs_profile() returns trigger
language plpgsql as $fn$
begin
  if coalesce(nullif(current_setting('request.jwt.claims', true), '')::json ->> 'role', '') = 'service_role' then
    return new;
  end if;
  if public.bc_has_slur(new.nickname) or public.bc_has_slur(new.bio) or public.bc_has_slur(new.username) then
    raise exception 'auto-mod: that name or bio contains blocked language';
  end if;
  return new;
end $fn$;

drop trigger if exists bc_slur_messages on public.messages;
create trigger bc_slur_messages before insert or update of content on public.messages
  for each row execute function public.bc_block_slurs();

drop trigger if exists bc_slur_dm on public.dm_messages;
create trigger bc_slur_dm before insert or update of content on public.dm_messages
  for each row execute function public.bc_block_slurs();

drop trigger if exists bc_slur_group on public.group_dm_messages;
create trigger bc_slur_group before insert or update of content on public.group_dm_messages
  for each row execute function public.bc_block_slurs();

drop trigger if exists bc_slur_profile on public.profiles;
create trigger bc_slur_profile before insert or update of username, nickname, bio on public.profiles
  for each row execute function public.bc_block_slurs_profile();
'''
open(os.path.join(root, 'setup', 'slur_filter.sql'), 'w', encoding='utf8').write(SQL)
print('wrote automod.js and setup/slur_filter.sql')
